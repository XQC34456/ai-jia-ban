"""P2-A Free→VIP 价值前置：Free 触发情景模拟时，先给基础判断，再展示 VIP 能继续提供的具体分析。

铁律：
- 本模块只产出「定性话术模板」，绝不计算、绝不编造财富数字（数字只来自 metrics/source）。
- 基础判断是方向性结论（收入/负债/配置如何变），不是具体数值，不触碰 Engine/Decision。
- 与 LLM 的关系：advisor 路径基础判断由 LLM 定性产出（本模块只补「进一步分析」边界）；
  确定性兜底路径则本模块连基础判断一并给出（无 LLM 时仍能交付价值）。
"""
from __future__ import annotations

__all__ = ["VIP_BOUNDARY", "value_first"]

# advisor 路径专用：情景名未知（LLM 在 tool 调用里才选场景），用通用「进一步分析」边界。
VIP_BOUNDARY = (
    "VIP 可以继续为你做完整的情景模拟：把这个变化对应急储备、负债率、资产配置、"
    "养老准备等九项指标的影响逐项算出来，并把「当前方案」与「压力情景」做可视化对比。"
)

# 确定性兜底路径专用：按 frozen scenario name 给（基础判断, 进一步分析），全定性、无数字。
_VALUE_FIRST: dict[str, tuple[str, str]] = {
    "income_change": (
        "按你当前家庭收支结构，收入下降后月度结余会明显收窄，现金流安全边际和应急缓冲都会变薄。",
        "VIP 可以继续模拟收入变化后的应急储备、负债率和资产配置变化，"
        "并把当前方案与压力情景做可视化对比。",
    ),
    "buy_house": (
        "买房会一次性占用大量现金、并新增房贷月供，对你当前的现金流和负债率都是明显压力。",
        "VIP 可以继续模拟买房后的现金流、负债率和养老准备变化，"
        "并对比不同房价、首付比例和贷款年限。",
    ),
    "prepay": (
        "提前还贷会减少现金储备，但能降低未来利息支出、改善现金流结构，具体效果取决于还款方式。",
        "VIP 可以继续模拟提前还贷后月供、现金流和净资产的变化，"
        "并对比「缩短年限」与「减少月供」两种方式。",
    ),
    "invest": (
        "投资会改变你的资产配置和现金缓冲，收益与风险并存，需要结合当前配置集中度来判断。",
        "VIP 可以继续模拟这笔投资对资产配置、现金流和财富评分的影响，并对比不同投向。",
    ),
}

_DEFAULT_VALUE_FIRST: tuple[str, str] = (
    "先看当前家庭的现金流与主要风险，这是判断任何情景影响的基础。",
    VIP_BOUNDARY,
)


def value_first(scenario: str | None) -> tuple[str, str]:
    """返回 (基础判断, 进一步分析)。未知/缺失场景 → 通用兜底。"""
    return _VALUE_FIRST.get(scenario or "", _DEFAULT_VALUE_FIRST)
